//! Build script: macOS SDK path for linking, plus generated built-in query pack embeddings.

use std::fs;
use std::path::{Path, PathBuf};

struct QueryPackBuildInput {
    pack_id: String,
    query_file_name: &'static str,
    query_path: PathBuf,
    has_injections: bool,
    has_metadata: bool,
}

fn pack_query_file(dir: &Path) -> Option<(&'static str, PathBuf)> {
    let tags = dir.join("tags.scm");
    if tags.is_file() {
        return Some(("tags.scm", tags));
    }

    let symbols = dir.join("symbols.scm");
    if symbols.is_file() {
        return Some(("symbols.scm", symbols));
    }

    None
}

fn generate_builtin_query_packs() {
    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let queries_root = manifest_dir.join("runtime/queries");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));

    let mut pack_dirs: Vec<QueryPackBuildInput> = Vec::new();
    for entry in fs::read_dir(&queries_root).unwrap_or_else(|e| {
        panic!("read_dir {}: {e}", queries_root.display());
    }) {
        let entry = entry.expect("dir entry");
        if !entry.file_type().expect("file_type").is_dir() {
            continue;
        }
        let path = entry.path();
        let Some((query_file_name, query_path)) = pack_query_file(&path) else {
            continue;
        };

        pack_dirs.push(QueryPackBuildInput {
            pack_id: entry.file_name().to_string_lossy().into_owned(),
            query_file_name,
            query_path,
            has_injections: path.join("injections.scm").is_file(),
            has_metadata: path.join("pack.toml").is_file(),
        });
    }
    pack_dirs.sort_by(|a, b| a.pack_id.cmp(&b.pack_id));

    let dst = out_dir.join("builtin_query_packs.rs");
    let mut buf = String::new();
    buf.push_str("// Built-in query packs — generated by `build.rs` from `runtime/queries/*`.\n");
    buf.push_str("// Pack id is the directory name under `runtime/queries/`.\n\n");
    buf.push_str(
        "pub const BUILTIN_QUERY_PACKS: &[(&str, &str, &str, Option<&str>, Option<&str>)] = &[\n",
    );
    for pack in &pack_dirs {
        let query_path = format!("/runtime/queries/{}/{}", pack.pack_id, pack.query_file_name);
        let injections_expr = if pack.has_injections {
            format!(
                "Some(include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/runtime/queries/{}/injections.scm\")))",
                pack.pack_id
            )
        } else {
            "None".to_string()
        };
        let metadata_expr = if pack.has_metadata {
            format!(
                "Some(include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/runtime/queries/{}/pack.toml\")))",
                pack.pack_id
            )
        } else {
            "None".to_string()
        };
        buf.push_str(&format!(
            "    (\"{}\", \"{}\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"{}\")), {}, {}),\n",
            pack.pack_id, pack.query_file_name, query_path, injections_expr, metadata_expr
        ));
    }
    buf.push_str("];\n\n");
    buf.push_str("pub const QUERY_FILES: &[(&str, &str)] = &[\n");
    for pack in &pack_dirs {
        let query_path = format!("/runtime/queries/{}/{}", pack.pack_id, pack.query_file_name);
        buf.push_str(&format!(
            "    (\"{}\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"{}\"))),\n",
            pack.pack_id, query_path
        ));
    }
    buf.push_str("];\n");

    fs::write(&dst, buf).unwrap_or_else(|e| panic!("write {}: {e}", dst.display()));

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=runtime/queries");
    for pack in &pack_dirs {
        println!(
            "cargo:rerun-if-changed={}",
            pack.query_path
                .strip_prefix(&manifest_dir)
                .unwrap()
                .display()
        );
        if pack.has_injections {
            println!(
                "cargo:rerun-if-changed=runtime/queries/{}/injections.scm",
                pack.pack_id
            );
        }
        if pack.has_metadata {
            println!(
                "cargo:rerun-if-changed=runtime/queries/{}/pack.toml",
                pack.pack_id
            );
        }
    }
}

#[cfg(target_os = "macos")]
fn macos_link_sdk() {
    if std::env::var_os("SDKROOT").is_some() {
        return;
    }

    let output = match std::process::Command::new("xcrun")
        .args(["--show-sdk-path"])
        .output()
    {
        Ok(output) if output.status.success() => output,
        _ => return,
    };

    let sdk_root = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if sdk_root.is_empty() {
        return;
    }

    println!("cargo:rustc-link-arg=-isysroot");
    println!("cargo:rustc-link-arg={sdk_root}");
}

#[cfg(target_os = "macos")]
fn main() {
    generate_builtin_query_packs();
    macos_link_sdk();
}

#[cfg(not(target_os = "macos"))]
fn main() {
    generate_builtin_query_packs();
}
