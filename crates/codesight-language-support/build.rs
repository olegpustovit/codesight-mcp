//! Build-time query pack discovery.
//!
//! Builtin packs live under `src/languages/<pack>/queries/` — each SCM file
//! sits next to the Rust code for its language. Extractors read the
//! generated `BUILTIN_QUERY_PACKS` table; this build script just wires the
//! SCM files into `include_str!` so adding a language stays a one-PR move.

use std::fs;
use std::path::PathBuf;

struct QueryPackBuildInput {
    pack_id: String,
    has_injections: bool,
    has_metadata: bool,
}

fn generate_builtin_query_packs() {
    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let languages_root = manifest_dir.join("src/languages");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));

    let mut pack_dirs = Vec::<QueryPackBuildInput>::new();
    for entry in fs::read_dir(&languages_root).unwrap_or_else(|e| {
        panic!("read_dir {}: {e}", languages_root.display());
    }) {
        let entry = entry.expect("dir entry");
        if !entry.file_type().expect("file_type").is_dir() {
            continue;
        }
        let lang_dir = entry.path();
        let queries_dir = lang_dir.join("queries");
        let tags_path = queries_dir.join("tags.scm");
        if !tags_path.is_file() {
            continue;
        }
        let pack_id = entry.file_name().to_string_lossy().into_owned();
        pack_dirs.push(QueryPackBuildInput {
            pack_id,
            has_injections: queries_dir.join("injections.scm").is_file(),
            has_metadata: queries_dir.join("pack.toml").is_file(),
        });
    }
    pack_dirs.sort_by(|left, right| left.pack_id.cmp(&right.pack_id));

    let dst = out_dir.join("builtin_query_packs.rs");
    let mut buf = String::new();
    buf.push_str(
        "// Built-in query packs — generated by `build.rs` from `src/languages/*/queries/`.\n",
    );
    buf.push_str("// Pack id is the directory name under `src/languages/` inside this crate.\n\n");
    buf.push_str(
        "pub type BuiltinQueryPackRow = (&'static str, &'static str, Option<&'static str>, Option<&'static str>);\n",
    );
    buf.push_str("pub const BUILTIN_QUERY_PACKS: &[BuiltinQueryPackRow] = &[\n");
    for pack in &pack_dirs {
        let tags_path = format!("/src/languages/{}/queries/tags.scm", pack.pack_id);
        let injections_expr = if pack.has_injections {
            format!(
                "Some(include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/src/languages/{}/queries/injections.scm\")))",
                pack.pack_id
            )
        } else {
            "None".to_string()
        };
        let metadata_expr = if pack.has_metadata {
            format!(
                "Some(include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/src/languages/{}/queries/pack.toml\")))",
                pack.pack_id
            )
        } else {
            "None".to_string()
        };
        buf.push_str(&format!(
            "    (\"{}\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"{}\")), {}, {}),\n",
            pack.pack_id, tags_path, injections_expr, metadata_expr
        ));
    }
    buf.push_str("];\n");

    fs::write(&dst, buf).unwrap_or_else(|e| panic!("write {}: {e}", dst.display()));

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", languages_root.display());
}

#[cfg(target_os = "macos")]
fn macos_link_sdk() {
    if std::env::var_os("SDKROOT").is_some() {
        return;
    }

    let output = match std::process::Command::new("xcrun")
        .args(["--show-sdk-path"])
        .output()
    {
        Ok(output) if output.status.success() => output,
        _ => return,
    };

    let sdk_root = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if sdk_root.is_empty() {
        return;
    }

    println!("cargo:rustc-link-arg=-isysroot");
    println!("cargo:rustc-link-arg={sdk_root}");
}

#[cfg(target_os = "macos")]
fn main() {
    generate_builtin_query_packs();
    macos_link_sdk();
}

#[cfg(not(target_os = "macos"))]
fn main() {
    generate_builtin_query_packs();
}
